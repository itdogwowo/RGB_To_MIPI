"""Generate the shield schematic v3: real SSD2828QN4R + real DFR connectors.

Wiring style: every pin gets a short stub + NET attribute (label). Nets join by name.
This avoids long bus routing errors and keeps the drawing collision-checkable.

Usage: gen2.py <project-dir>
"""
import json, os, subprocess, sys, collections

SKILL = "/Users/tungkinlee/Documents/Git/Sourcetree/RGB_To_MIPI/.git/scratch/easyeda-eprj3-skill"
DIR = sys.argv[1]
SCH, SHEET = "SCH", "P1"
STUB = 30

def run(*a, check=True):
    r = subprocess.run(["node", *a], cwd=SKILL, capture_output=True, text=True)
    if check and r.returncode != 0:
        print("FAIL", a[:3], r.stdout[-800:], r.stderr[-800:]); sys.exit(1)
    return r

def lib(name):
    for base in (os.path.join(DIR, ".tmp", "library", "symbol"),
                 os.path.join(SKILL, "templates", "library", "symbol")):
        fn = os.path.join(base, name + ".json")
        if os.path.exists(fn):
            return json.load(open(fn))
    raise FileNotFoundError(name)

def pins_of(entry):
    out = []
    for line in entry["symbolDoc"]:
        head, _, body = line.partition("||")
        if body.endswith("|"):
            body = body[:-1]
        try:
            h = json.loads(head)
        except Exception:
            continue
        if h.get("type") != "PIN":
            continue
        try:
            b = json.loads(body)
        except Exception:
            b = {}
        out.append(dict(id=h["id"], x=b.get("x", 0), y=b.get("y", 0),
                        ln=b.get("length", 10), rot=b.get("rotation", 0)))
    # pin number/name from ATTRs
    attrs = collections.defaultdict(dict)
    for line in entry["symbolDoc"]:
        head, _, body = line.partition("||")
        if body.endswith("|"):
            body = body[:-1]
        try:
            h = json.loads(head)
        except Exception:
            continue
        if h.get("type") != "ATTR":
            continue
        try:
            b = json.loads(body)
        except Exception:
            continue
        attrs[b.get("parentId")][b.get("key")] = b.get("value")
    for p in out:
        p["num"] = str(attrs[p["id"]].get("Pin Number"))
        p["name"] = str(attrs[p["id"]].get("Pin Name"))
    return out

PINS = {}

def place(ref, entry_name, x, y, rot=0):
    run("scripts/add-symbol.js", "--dir", DIR, "--sch", SCH, "--sheet", SHEET,
        "--symbol", entry_name, "--x", str(x), "--y", str(y),
        "--rotation", str(rot), "--refdes", ref, "--name", entry_name)
    PINS[ref] = dict(entry=entry_name, x=x, y=y, rot=rot, pins=pins_of(lib(entry_name)))

def anchor_pt(ref, p):
    """the client connects wires at the pin anchor (px,py), not at the outer tip"""
    c = PINS[ref]
    rot = int(c["rot"]) % 360
    dx, dy = p["x"], p["y"]
    base = [(c["x"] + dx, c["y"] + dy), (c["x"] - dy, c["y"] + dx),
            (c["x"] - dx, c["y"] - dy), (c["x"] + dy, c["y"] - dx)]
    return base[rot // 90]


def tip(ref, p):
    return anchor_pt(ref, p)


def direction(ref, p):
    c = PINS[ref]
    rot = int(c["rot"]) % 360
    vx, vy = {0: (-1, 0), 90: (0, -1), 180: (1, 0), 270: (0, 1)}.get(int(p["rot"]) % 360, (-1, 0))
    base = [(vx, vy), (-vy, vx), (-vx, -vy), (vy, -vx)]
    return base[rot // 90]

def stub(ref, pin_sel, net):
    """draw a stub from the selected pin and name it"""
    p = pin_sel
    t = tip(ref, p)
    d = direction(ref, p)
    end = (t[0] + d[0] * STUB, t[1] + d[1] * STUB)
    run("scripts/add-wire.js", "--dir", DIR, "--sch", SCH, "--sheet", SHEET,
        "--segs", f"{t[0]},{t[1]},{end[0]},{end[1]}", "--net", net)

def wire_by_num(ref, table):
    for p in PINS[ref]["pins"]:
        net = table.get(p["num"])
        if net:
            stub(ref, p, net)

def wire_by_name(ref, table):
    for p in PINS[ref]["pins"]:
        net = table.get(p["name"])
        if net:
            stub(ref, p, net)

